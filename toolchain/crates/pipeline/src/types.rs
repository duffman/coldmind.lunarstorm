//! TypeScript declarations of the model (spec 2.5, 4 "Typecheck"), generated
//! from the element table so `tsc` checks a project against the same schema the
//! compiler enforces.
//!
//! One file, written into a project as `src/desktop.d.ts`, declares:
//! - `@desktop/forms`: `Form`, `CloseQuery` and one interface per control kind,
//!   whose members are the props a form class may read and write;
//! - `@desktop/api`: `native`;
//! - the JSX elements of view and application resources.
//!
//! Decisions:
//! - The file has no top-level import or export, so its `declare module` blocks
//!   and the `JSX` namespace are ambient: a project needs no `paths` mapping and
//!   no installed package to type-check.
//! - An event prop accepts any function. Which handler a resource connects is
//!   checked by the compiler against the form class (spec 4a); `tsc` only has to
//!   see that it is a member.
//! - Runtime-only props (`rows`, `nodes`) are members of the control interfaces
//!   but not JSX attributes: markup may not set them (spec 2.4).
//! - `native` is typed loosely here; its methods are the host's API surface and
//!   are checked against the permissions at build time, not by `tsc`.

use lunarstorm_model::schema::{class_name, Kind, PropSpec, Type, KINDS};

/// The TypeScript type of a prop.
///
/// # Arguments
/// * `ty` - the prop's schema type.
/// * `attribute` - `true` for a JSX attribute, where arrays may be readonly
///   literals; `false` for a member of a control interface.
///
/// # Returns
/// The type as TypeScript source.
fn type_of(ty: Type, attribute: bool) -> String {
    let array = if attribute { "readonly " } else { "" };
    let union = |values: &[&str]| values.iter().map(|value| format!("'{value}'")).collect::<Vec<_>>().join(" | ");
    match ty {
        Type::Text | Type::Color | Type::Ref(_) => "string".into(),
        Type::Number => "number".into(),
        Type::Bool => "boolean".into(),
        Type::Texts => format!("{array}string[]"),
        Type::Choice(values) => union(values),
        Type::Choices(values) => format!("{array}({})[]", union(values)),
        Type::Rows => "string[][]".into(),
        Type::Nodes => "TreeNode[]".into(),
    }
}

/// Writes the interface of one control kind.
///
/// # Arguments
/// * `kind` - the element.
/// * `name` - its class name.
/// * `out` - the declarations being written.
fn control(kind: &Kind, name: &str, out: &mut String) {
    out.push_str(&format!("  /** A `<{}>` of a form, as its form class sees it. */\n  export interface {name} {{\n", kind.tag));
    out.push_str("    /** The control's name in its form. */\n    readonly name: string;\n");
    for PropSpec { name, ty, .. } in kind.all_props() {
        out.push_str(&format!("    {name}: {};\n", type_of(*ty, false)));
    }
    out.push_str("  }\n");
}

/// Writes the JSX attributes of one element.
///
/// # Arguments
/// * `kind` - the element.
/// * `out` - the declarations being written.
fn element(kind: &Kind, out: &mut String) {
    out.push_str(&format!("    {}: {{\n", kind.tag));
    // `<form>` is named although it is not a control: the name is its class's.
    if kind.named {
        out.push_str("      name: string;\n");
    }
    for spec in kind.all_props().filter(|spec| spec.declared) {
        out.push_str(&format!("      {}?: {};\n", spec.name, type_of(spec.ty, true)));
    }
    for event in kind.events {
        out.push_str(&format!("      {event}?: Handler;\n"));
    }
    if kind.common {
        // Every visual control can ask for its popup menu.
        out.push_str("      onContextPopup?: Handler;\n");
    }
    out.push_str("      children?: unknown;\n    };\n");
}

/// Generates the declarations file.
///
/// # Returns
/// The text of `desktop.d.ts`.
pub fn declarations() -> String {
    let mut out = String::from(
        "// Generated by `lunarstorm-build --types`. Do not edit.\n\ndeclare module '@desktop/forms' {\n  /** A node of a `<treeview>`. */\n  export interface TreeNode {\n    /** Identifies the node; unique within its tree. */\n    id: string;\n    /** The node's text. */\n    caption: string;\n    /** The node's children. */\n    children?: TreeNode[];\n  }\n\n  /** The argument of `onCloseQuery`. */\n  export interface CloseQuery {\n    /** Set to `true` to keep the form open. */\n    cancel: boolean;\n  }\n\n  /** The base class of every form class (spec 2.5). */\n  export class Form {\n    /** The form's name. */\n    readonly name: string;\n    /**\n     * Returns a control of this form. The compiler resolves the name and `T`\n     * against the form's view resource.\n     * @param name the control's name\n     * @return the control\n     */\n    protected find<T = unknown>(name: string): T;\n  }\n\n",
    );
    for kind in KINDS {
        if let Some(name) = class_name(kind.tag) {
            control(kind, name, &mut out);
        }
    }
    out.push_str("}\n\ndeclare module '@desktop/api' {\n  /** The host's native API: `native.<namespace>.<method>(...)`. */\n  export const native: Readonly<Record<string, Readonly<Record<string, (...args: any[]) => Promise<any>>>>>;\n}\n\ndeclare namespace JSX {\n  /** An event connection: a member of the form class. */\n  type Handler = (...args: any[]) => unknown;\n  /** A resource is data for the compiler; it is never rendered. */\n  type Element = unknown;\n  /** Children are the nested elements. */\n  interface ElementChildrenAttribute {\n    children: unknown;\n  }\n  /** The elements of view and application resources (spec 2.4, 2.6). */\n  interface IntrinsicElements {\n");
    for kind in KINDS {
        element(kind, &mut out);
    }
    out.push_str("  }\n}\n");
    out
}

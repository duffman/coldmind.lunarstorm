//! The `.d.ts` emitter: TypeScript declarations from the Runtime's [`ModuleDecl`]s.
//!
//! `lunarstorm types` collects each host's declarations and calls [`emit`]; the
//! files it returns are committed under `runtime/typescript-declarations/dist/`, the npm package
//! `lunartypes`. `tests/generated.rs` fails when they are stale.
//!
//! Decisions:
//! - One file per layer (plan D5): `index.d.ts` holds what every host offers,
//!   `<host>.d.ts` and `extensions/<name>.d.ts` hold only what that layer adds and
//!   reference the layers below with `/// <reference path>`. A module a layer adds
//!   to is declared again there; TypeScript merges ambient module declarations.
//! - `lunarstorm:internal` is emitted, under its real specifier, as the interface
//!   `Ops` plus `export const ops: Ops`: that module's one declared export is the
//!   `ops` object and its items are that object's members, not exports. Kept
//!   rather than skipped because host modules and third-party extension JS import
//!   it; it stays out of user programs because the Runtime refuses the import
//!   outside host modules. A layer that adds to it only extends `Ops`.
//! - Globals go to `globals.d.ts` inside `declare global { … }`, referenced from
//!   `index.d.ts`, and the file exists only when a global is declared. A
//!   `declare global` block needs a module file, and a module file turns every
//!   `declare module "x"` in it into an augmentation, so the two cannot share one.
//! - Output is deterministic: declaration order, LF, 2-space indent, no blank
//!   lines inside a module.

use lunarstorm_engine_contract::{ClassDecl, Field, FnDecl, Item, ModuleDecl, Param, Sig, Ty};
use std::fmt::Write as _;
use std::path::PathBuf;

/// The module whose items are the members of its `ops` export.
pub const INTERNAL: &str = "lunarstorm:internal";

/// The first line of every emitted file.
const HEADER: &str = "// Generated by `lunarstorm types` from the Runtime's declarations. Do not edit.\n";

/// What one host adds to the core.
#[derive(Debug, Clone)]
pub struct Host {
    /// The file name without `.d.ts`: `cli`, `desktop`.
    pub name: &'static str,
    /// The host's own modules and items, without the core's or its extensions'.
    pub modules: Vec<ModuleDecl>,
    /// The extensions (keys of [`Surface::extensions`]) this host installs.
    pub extensions: Vec<&'static str>,
}

/// Everything [`emit`] writes, already split into layers.
#[derive(Debug, Clone, Default)]
pub struct Surface {
    /// What every host offers: `index.d.ts`.
    pub core: Vec<ModuleDecl>,
    /// Globals every host installs. None are declared yet.
    pub globals: Vec<Item>,
    /// One entry per extension: its name and what it adds to the core.
    pub extensions: Vec<(&'static str, Vec<ModuleDecl>)>,
    /// One entry per host.
    pub hosts: Vec<Host>,
}

/// Renders the declaration files.
///
/// # Arguments
/// * `surface` - the declarations, split into layers.
///
/// # Returns
/// `(path relative to the output directory, contents)` per file: `index.d.ts`,
/// `globals.d.ts` (when there are globals), `extensions/<name>.d.ts`, then
/// `<host>.d.ts`, each in input order.
pub fn emit(surface: &Surface) -> Vec<(PathBuf, String)> {
    let mut index_refs = Vec::new();
    let mut rest = Vec::new();
    if !surface.globals.is_empty() {
        index_refs.push(String::from("./globals.d.ts"));
        let mut text = format!("{HEADER}export {{}};\n\ndeclare global {{\n");
        for item in &surface.globals {
            export(&mut text, "  ", "", item);
        }
        text.push_str("}\n");
        rest.push((PathBuf::from("globals.d.ts"), text));
    }
    for (name, modules) in &surface.extensions {
        rest.push((PathBuf::from(format!("extensions/{name}.d.ts")), file(&[String::from("../index.d.ts")], modules, &surface.core)));
    }
    for host in &surface.hosts {
        let mut refs = vec![String::from("./index.d.ts")];
        let mut base = surface.core.clone();
        for name in &host.extensions {
            refs.push(format!("./extensions/{name}.d.ts"));
            base.extend(surface.extensions.iter().filter(|(known, _)| known == name).flat_map(|(_, modules)| modules.iter().cloned()));
        }
        rest.push((PathBuf::from(format!("{}.d.ts", host.name)), file(&refs, &host.modules, &base)));
    }
    let mut files = vec![(PathBuf::from("index.d.ts"), file(&index_refs, &surface.core, &[]))];
    files.extend(rest);
    files
}

/// # Arguments
/// * `a` - one host's declarations.
/// * `b` - another host's.
///
/// # Returns
/// The items both declare identically, in `a`'s order; modules left empty are dropped.
pub fn common(a: &[ModuleDecl], b: &[ModuleDecl]) -> Vec<ModuleDecl> {
    filter(a, |specifier, item| find(b, specifier).is_some_and(|module| module.items.contains(item)))
}

/// # Arguments
/// * `all` - a layer's declarations, including those of the layers below.
/// * `base` - the layers below.
///
/// # Returns
/// The items of `all` that `base` does not declare identically, in order; modules
/// left empty are dropped.
pub fn only(all: &[ModuleDecl], base: &[ModuleDecl]) -> Vec<ModuleDecl> {
    filter(all, |specifier, item| !find(base, specifier).is_some_and(|module| module.items.contains(item)))
}

/// # Arguments
/// * `modules` - the modules to search.
/// * `specifier` - the module's specifier.
///
/// # Returns
/// The module with that specifier, if any.
fn find<'m>(modules: &'m [ModuleDecl], specifier: &str) -> Option<&'m ModuleDecl> {
    modules.iter().find(|module| module.specifier == specifier)
}

/// # Arguments
/// * `modules` - the modules to filter.
/// * `keep` - whether an item of a module (by specifier) stays.
///
/// # Returns
/// The modules with only the kept items; empty ones dropped.
fn filter(modules: &[ModuleDecl], keep: impl Fn(&str, &Item) -> bool) -> Vec<ModuleDecl> {
    modules
        .iter()
        .map(|module| ModuleDecl { items: module.items.iter().filter(|item| keep(module.specifier, item)).copied().collect(), ..module.clone() })
        .filter(|module| !module.items.is_empty())
        .collect()
}

/// Renders one file of ambient module declarations.
///
/// # Arguments
/// * `references` - paths for `/// <reference path>`, relative to this file.
/// * `modules` - the modules this file declares or adds to.
/// * `base` - the layers below; a module they declare is only added to here.
///
/// # Returns
/// The file's text.
fn file(references: &[String], modules: &[ModuleDecl], base: &[ModuleDecl]) -> String {
    let mut out = String::from(HEADER);
    for path in references {
        let _ = writeln!(out, "/// <reference path=\"{path}\" />");
    }
    for module in modules {
        out.push('\n');
        doc(&mut out, "", module.about, &[]);
        let _ = writeln!(out, "declare module \"{}\" {{", module.specifier);
        if module.specifier == INTERNAL {
            internal(&mut out, module, find(base, INTERNAL).is_some());
        } else {
            for item in &module.items {
                export(&mut out, "  ", "export ", item);
            }
        }
        out.push_str("}\n");
    }
    out
}

/// Renders the body of `lunarstorm:internal`: its classes, the `Ops` interface
/// and, unless a lower layer already declared it, the `ops` constant.
///
/// # Arguments
/// * `out` - where to write.
/// * `module` - the internal module's declarations in this layer.
/// * `augments` - whether a lower layer declared the module.
fn internal(out: &mut String, module: &ModuleDecl, augments: bool) {
    for item in &module.items {
        if let Item::Class(_) = item {
            export(out, "  ", "export ", item);
        }
    }
    out.push_str("  /** The members of `ops`. */\n  export interface Ops {\n");
    for item in &module.items {
        match item {
            Item::Function(FnDecl { name, sig }) => {
                doc(out, "    ", sig.about, sig.params);
                let _ = writeln!(out, "    {name}({}): {};", params(sig), returns(&sig.returns));
            }
            Item::Class(class) => {
                doc(out, "    ", class.about, &[]);
                let _ = writeln!(out, "    {}: typeof {};", class.name, class.name);
            }
            Item::Value(field) => {
                doc(out, "    ", field.about, &[]);
                let _ = writeln!(out, "    {};", member(field));
            }
        }
    }
    out.push_str("  }\n");
    if !augments {
        out.push_str("  /** The Runtime's natives and the host's, for host modules. */\n  export const ops: Ops;\n");
    }
}

/// Renders one declaration with its JSDoc.
///
/// # Arguments
/// * `out` - where to write.
/// * `indent` - the indent of the declaration.
/// * `prefix` - `export ` inside a module, empty inside `declare global`.
/// * `item` - the declaration.
fn export(out: &mut String, indent: &str, prefix: &str, item: &Item) {
    match item {
        Item::Function(FnDecl { name, sig }) => {
            doc(out, indent, sig.about, sig.params);
            let _ = writeln!(out, "{indent}{prefix}function {name}({}): {};", params(sig), returns(&sig.returns));
        }
        Item::Value(field) => {
            doc(out, indent, field.about, &[]);
            let _ = writeln!(out, "{indent}{prefix}const {}: {};", field.name, ts(&field.ty));
        }
        Item::Class(class) => self::class(out, indent, prefix, class),
    }
}

/// Renders a class: constructor, methods, accessors (as properties: a declaration
/// does not say whether one is read-only) and statics.
///
/// # Arguments
/// * `out` - where to write.
/// * `indent` - the indent of the class line.
/// * `prefix` - `export ` or empty.
/// * `class` - the declaration.
fn class(out: &mut String, indent: &str, prefix: &str, class: &ClassDecl) {
    doc(out, indent, class.about, &[]);
    let extends = class.extends.map(|base| format!(" extends {base}")).unwrap_or_default();
    let _ = writeln!(out, "{indent}{prefix}class {}{extends} {{", class.name);
    let inner = format!("{indent}  ");
    doc(out, &inner, class.constructor.about, class.constructor.params);
    let _ = writeln!(out, "{inner}constructor({});", params(&class.constructor));
    for field in class.accessors {
        doc(out, &inner, field.about, &[]);
        let _ = writeln!(out, "{inner}{};", member(field));
    }
    for (keyword, methods) in [("", class.methods), ("static ", class.statics)] {
        for FnDecl { name, sig } in methods {
            doc(out, &inner, sig.about, sig.params);
            let _ = writeln!(out, "{inner}{keyword}{name}({}): {};", params(sig), returns(&sig.returns));
        }
    }
    let _ = writeln!(out, "{indent}}}");
}

/// Writes a JSDoc comment: the summary, then one `@param` per documented parameter.
///
/// # Arguments
/// * `out` - where to write.
/// * `indent` - the indent of the commented declaration.
/// * `about` - the summary; nothing is written when it and every parameter's are empty.
/// * `params` - the parameters.
fn doc(out: &mut String, indent: &str, about: &str, params: &[Param]) {
    // A `*/` inside the text would end the comment early.
    let clean = |text: &str| text.replace("*/", "*\\/");
    let mut lines: Vec<String> = Vec::new();
    if !about.is_empty() {
        lines.push(clean(about));
    }
    lines.extend(params.iter().filter(|param| !param.about.is_empty()).map(|param| format!("@param {} {}", param.name, clean(param.about))));
    match lines.as_slice() {
        [] => {}
        [only] if params.iter().all(|param| param.about.is_empty()) => {
            let _ = writeln!(out, "{indent}/** {only} */");
        }
        _ => {
            let _ = writeln!(out, "{indent}/**");
            for line in &lines {
                let _ = writeln!(out, "{indent} * {line}");
            }
            let _ = writeln!(out, "{indent} */");
        }
    }
}

/// # Arguments
/// * `sig` - a signature.
///
/// # Returns
/// Its parameter list, without parentheses.
///
/// Decision: an `Optional` parameter is written `name?: T` only when every
/// parameter after it is optional too; before a required one TypeScript forbids
/// `?`, so it is written `name: T | undefined`, which still accepts `undefined`.
fn params(sig: &Sig) -> String {
    let mut parts: Vec<String> = sig
        .params
        .iter()
        .enumerate()
        .map(|(index, param)| match param.ty {
            Ty::Optional(inner) if sig.params[index..].iter().all(|later| matches!(later.ty, Ty::Optional(_))) => format!("{}?: {}", param.name, ts(inner)),
            ty => format!("{}: {}", param.name, ts(&ty)),
        })
        .collect();
    if let Some(rest) = &sig.rest {
        parts.push(format!("...{}: {}[]", rest.name, grouped(&rest.ty)));
    }
    parts.join(", ")
}

/// # Arguments
/// * `field` - an object field, accessor or `Ops` value.
///
/// # Returns
/// `name: T`, or `name?: T` when the field is `Optional`.
fn member(field: &Field) -> String {
    match field.ty {
        Ty::Optional(inner) => format!("{}?: {}", field.name, ts(inner)),
        ty => format!("{}: {}", field.name, ts(&ty)),
    }
}

/// # Arguments
/// * `ty` - a type.
///
/// # Returns
/// Its TypeScript spelling, parenthesized when it would otherwise bind loosely
/// (a union, an optional or a function type as an array item or union member).
fn grouped(ty: &Ty) -> String {
    match ty {
        Ty::Union(_) | Ty::Optional(_) | Ty::Function(_) => format!("({})", ts(ty)),
        _ => ts(ty),
    }
}

/// # Arguments
/// * `ty` - a function's return type.
///
/// # Returns
/// Its TypeScript spelling, with `undefined` written `void`.
///
/// Decision: `void`, as TypeScript declares a function that returns nothing; a
/// callback typed `=> undefined` would reject every callback that returns a value,
/// which JS ignores.
fn returns(ty: &Ty) -> String {
    match ty {
        Ty::Undefined => String::from("void"),
        _ => ts(ty),
    }
}

/// # Arguments
/// * `ty` - a type.
///
/// # Returns
/// Its TypeScript spelling. `Optional` outside a parameter or field is
/// `T | undefined`; an `Object` with no fields is `object`.
fn ts(ty: &Ty) -> String {
    match ty {
        Ty::Undefined => String::from("undefined"),
        Ty::Null => String::from("null"),
        Ty::Bool => String::from("boolean"),
        Ty::Number => String::from("number"),
        Ty::String => String::from("string"),
        Ty::Bytes => String::from("Uint8Array"),
        Ty::Any => String::from("any"),
        Ty::Unknown => String::from("unknown"),
        Ty::Array(item) => format!("{}[]", grouped(item)),
        Ty::Object([]) => String::from("object"),
        Ty::Object(fields) => format!("{{ {} }}", fields.iter().map(member).collect::<Vec<_>>().join("; ")),
        Ty::Union(types) => types.iter().map(|ty| if let Ty::Function(_) = ty { grouped(ty) } else { ts(ty) }).collect::<Vec<_>>().join(" | "),
        Ty::Promise(ty) => format!("Promise<{}>", ts(ty)),
        Ty::Function(sig) => format!("({}) => {}", params(sig), returns(&sig.returns)),
        Ty::Named(name) => String::from(*name),
        Ty::Optional(ty) => format!("{} | undefined", ts(ty)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const NAME: Param = Param { name: "name", ty: Ty::Optional(&Ty::String), about: "" };
    const ON: Sig = Sig {
        params: &[NAME, Param { name: "listener", ty: Ty::Function(&Sig { params: &[], rest: None, returns: Ty::Undefined, about: "" }), about: "" }],
        rest: Some(Param { name: "more", ty: Ty::Union(&[Ty::Number, Ty::Bytes]), about: "" }),
        returns: Ty::Promise(&Ty::Array(&Ty::Optional(&Ty::Named("Emitter")))),
        about: "Adds */ a listener.",
    };

    /// A class, an optional before a required parameter, a rest union, globals and
    /// a host layer that only adds to a core module.
    #[test]
    fn renders_classes_params_globals_and_layers() {
        let emitter = ClassDecl {
            name: "Emitter",
            extends: Some("Uint8Array"),
            constructor: Sig { params: &[NAME], rest: None, returns: Ty::Undefined, about: "" },
            methods: &[FnDecl { name: "on", sig: ON }],
            accessors: &[Field { name: "size", ty: Ty::Object(&[Field { name: "a", ty: Ty::Optional(&Ty::Bool), about: "" }]), about: "x" }],
            statics: &[FnDecl { name: "of", sig: Sig { params: &[], rest: None, returns: Ty::Unknown, about: "" } }],
            about: "Emits.",
        };
        let core = vec![ModuleDecl { specifier: "node:events", items: vec![Item::Class(emitter)], about: "Events." }];
        let more = ModuleDecl { specifier: "node:events", items: vec![Item::Function(FnDecl { name: "once", sig: ON })], about: "Events." };
        let surface = Surface {
            core: core.clone(),
            globals: vec![Item::Value(Field { name: "version", ty: Ty::String, about: "" })],
            extensions: Vec::new(),
            hosts: vec![Host { name: "cli", modules: only(&[core[0].clone(), more], &core), extensions: Vec::new() }],
        };
        let files = emit(&surface);
        let names: Vec<_> = files.iter().map(|(path, _)| path.to_str().unwrap()).collect();
        assert_eq!(names, ["index.d.ts", "globals.d.ts", "cli.d.ts"]);
        assert_eq!(
            files[0].1,
            format!(
                "{HEADER}/// <reference path=\"./globals.d.ts\" />\n\n/** Events. */\ndeclare module \"node:events\" {{\n  /** Emits. */\n  export class Emitter extends Uint8Array {{\n    constructor(name?: string);\n    /** x */\n    size: {{ a?: boolean }};\n    /** Adds *\\/ a listener. */\n    on(name: string | undefined, listener: () => void, ...more: (number | Uint8Array)[]): Promise<(Emitter | undefined)[]>;\n    static of(): unknown;\n  }}\n}}\n"
            )
        );
        assert_eq!(files[1].1, format!("{HEADER}export {{}};\n\ndeclare global {{\n  const version: string;\n}}\n"));
        assert!(files[2].1.contains("/// <reference path=\"./index.d.ts\" />\n\n/** Events. */\ndeclare module \"node:events\" {\n  /** Adds"), "{}", files[2].1);
        assert!(!files[2].1.contains("class Emitter"));
    }
}

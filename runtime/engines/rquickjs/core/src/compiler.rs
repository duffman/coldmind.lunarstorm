//! The Rust compiler (crates/qjs-*) as the context's only JavaScript compiler.
//!
//! Registered on every context with `jbq_set_compiler`, so scripts, modules,
//! indirect eval, `new Function` and direct/debugger eval all compile here and
//! install only images that passed the Rust image verifier.
//!
//! lunarstorm patch: jetbunny's `src/engines/quickjs_ng/compiler.rs`, moved
//! from `lunarstorm-debug` into rquickjs-core. With the C parser removed this
//! is the engine's only compiler, so every context rquickjs creates installs it
//! ([`install_base`]), not only the contexts the debugger wraps. Changes from
//! jetbunny's text, each marked: the private bridge declarations live in
//! [`bridge`] instead of `super::ffi`, and the debugger backend
//! (`QuickJsDebug`) is reached through [`CompileObserver`].
use self::bridge as ffi;
use qjs_bytecode::image::{eval, FunctionFlags, ScopeLink};
use qjs_compiler_core::js_emit::JsEmitOptions;
use qjs_frontend::source::SourceInput;
use std::ffi::{c_char, c_int, c_void, CStr, CString};
use std::string::{String, ToString};
use std::vec::Vec;
use std::format;

const EVAL_TYPE_MASK: c_int = 3;
const EVAL_TYPE_MODULE: c_int = 1;
/// lunarstorm patch: `JS_EVAL_FLAG_STRICT`, the caller forces strict mode.
const EVAL_FLAG_STRICT: c_int = 1 << 3;
const EVAL_FLAG_DEBUG: c_int = 1 << 8;
const EVAL_FLAG_FUNCTION: c_int = 1 << 10;

const SYNTAX: c_int = 1;
const RANGE: c_int = 2;
const INTERNAL: c_int = 3;

/// The kind of source a compile request carries, as the debugger registers it.
///
/// lunarstorm patch: mirrors `lunarstorm-debug`'s `ScriptKind`, which this
/// crate cannot name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SourceKind {
    /// Host-entered standalone source.
    Script,
    /// Native module source.
    Module,
    /// Application `eval` source discovered by the native engine.
    Eval,
    /// Source generated by a native `Function` constructor.
    Function,
}

/// The compiler's view of a debugger backend.
///
/// lunarstorm patch: jetbunny's compiler called `QuickJsDebug` directly; these
/// are exactly the calls it made, so `lunarstorm-debug` implements this trait
/// for its backend and passes it to [`install`].
pub trait CompileObserver {
    /// What [`CompileObserver::register_source`] hands back to
    /// [`CompileObserver::loaded`] for one compile.
    type Registration;
    /// Called once per compile request, before anything else (test counters).
    fn compiling(&self) {}
    /// # Returns
    /// Whether a debugger session is open: every compile is then a debug
    /// compile with markers.
    fn is_development(&self) -> bool;
    /// Registers the source about to be compiled.
    ///
    /// # Arguments
    /// * `source` - the UTF-16 source units.
    /// * `name` - the source's file name.
    /// * `kind` - what kind of source it is.
    ///
    /// # Returns
    /// The registration to pass to [`CompileObserver::loaded`], if any.
    ///
    /// # Errors
    /// The message of a refused registration; the compile then fails.
    fn register_source(
        &self,
        source: &[u16],
        name: &str,
        kind: SourceKind,
    ) -> Result<Option<Self::Registration>, String>;
    /// Called with the installed root after a successful compile.
    ///
    /// # Arguments
    /// * `root` - the compiled root the engine returned (borrowed).
    /// * `registration` - what [`CompileObserver::register_source`] returned.
    ///
    /// # Errors
    /// The message of a failed publication; the compile then fails.
    fn loaded(&self, root: Value, registration: Option<Self::Registration>) -> Result<(), String>;
}

/// The observer of a context without a debugger: nothing registers.
pub struct NoObserver;
impl CompileObserver for NoObserver {
    type Registration = ();
    fn is_development(&self) -> bool {
        false
    }
    fn register_source(&self, _: &[u16], _: &str, _: SourceKind) -> Result<Option<()>, String> {
        Ok(None)
    }
    fn loaded(&self, _: Value, _: Option<()>) -> Result<(), String> {
        Ok(())
    }
}

/// A bridge value: an engine `JSValue` packed byte for byte (`jbq_value`).
pub use self::bridge::Value;
/// The bridge's context (`jbq_context`), opaque.
pub use self::bridge::Context as BridgeContext;

/// Install the Rust compiler on a bridge context.
///
/// # Arguments
/// * `context` - the bridge context.
/// * `observer` - the debugger backend, or null for none; must stay valid
///   until the compiler is replaced or the bridge context is freed.
///
/// # Returns
/// `true` when installed.
///
/// # Safety
/// `context` is a live context owned by the calling thread.
pub unsafe fn install<O: CompileObserver>(context: *mut BridgeContext, observer: *const O) -> bool {
    // SAFETY: caller owns the live context and keeps the observer alive.
    unsafe { ffi::jbq_set_compiler(context, Some(compile::<O>), observer.cast_mut().cast()) == 0 }
}

/// lunarstorm patch: install the Rust compiler as the base compiler of an
/// engine context rquickjs created (`JS_JetbunnySetBaseCompiler`), with no
/// observer. A debugger may later install its own on top; releasing it falls
/// back to this one.
///
/// # Arguments
/// * `context` - the engine context.
///
/// # Returns
/// `true` when installed.
///
/// # Safety
/// `context` is a live engine context on the calling (owner) thread.
pub unsafe fn install_base(context: *mut rquickjs_sys::JSContext) -> bool {
    // SAFETY: caller owns the live context; NoObserver has no state.
    unsafe {
        ffi::jbq_set_base_compiler(context.cast(), Some(compile::<NoObserver>), core::ptr::null_mut())
            == 0
    }
}

/// The compiler callback `jbq_set_compiler` registers (jetbunny's `compile`).
///
/// lunarstorm patch: public so `lunarstorm-debug`'s boundary tests can drive
/// it directly, as they did when the function lived there.
///
/// # Safety
/// Called by the bridge with a live context, borrowed source and the opaque
/// [`install`] registered (an `O` or null).
pub unsafe extern "C" fn compile<O: CompileObserver>(
    opaque: *mut c_void,
    context: *mut ffi::Context,
    lease: u64,
    source: *const u16,
    units: usize,
    filename: *const c_char,
    _line: c_int,
    flags: c_int,
) -> ffi::Value {
    let outcome = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        // SAFETY: C lends these source units and the optional backend for this call.
        let debug = if opaque.is_null() {
            None
        } else {
            // SAFETY: ContextState retains the installed backend until native teardown.
            Some(unsafe { &*opaque.cast::<O>() })
        };
        // lunarstorm patch: jetbunny's `#[cfg(test)]` compile counter is the
        // observer's `compiling` hook.
        if let Some(debug) = debug {
            debug.compiling();
        }
        let source = if units == 0 {
            &[][..]
        } else {
            // SAFETY: the compiler callback borrows exactly units initialized UTF-16 units.
            unsafe { std::slice::from_raw_parts(source, units) }
        };
        let name = if filename.is_null() {
            String::from("<input>")
        } else {
            // SAFETY: native callback supplies a borrowed NUL-terminated name.
            unsafe { CStr::from_ptr(filename) }
                .to_string_lossy()
                .into_owned()
        };
        let flags = if debug.is_some_and(|d| d.is_development()) {
            flags | EVAL_FLAG_DEBUG
        } else {
            flags
        };
        let registration = if let Some(debug) = debug {
            debug
                .register_source(
                    source,
                    &name,
                    if flags & EVAL_TYPE_MASK == EVAL_TYPE_MODULE {
                        SourceKind::Module
                    } else if flags & EVAL_FLAG_FUNCTION != 0 {
                        SourceKind::Function
                    } else if lease != 0 || matches!(flags & EVAL_TYPE_MASK, 2 | 3) {
                        SourceKind::Eval
                    } else {
                        SourceKind::Script
                    },
                )
                .map_err(|error| (4, error))?
        } else {
            None
        };
        // SAFETY: owner context and synchronous frame lease stay live for compilation.
        let (bytes, module) = unsafe { compile_image(context, lease, source, &name, flags) }?;
        // SAFETY: only a verified image for this exact target reaches native loading.
        let root = unsafe {
            ffi::jbq_install_verified(context, bytes.as_ptr(), bytes.len(), c_int::from(module))
        };
        // SAFETY: root is the native result just returned by this context.
        if unsafe { ffi::jbq_is_exception(root) } != 0 {
            return Ok(root);
        }
        let guard = CompiledRoot {
            context,
            value: root,
        };
        if let Some(debug) = debug {
            debug
                .loaded(root, registration)
                .map_err(|error| (INTERNAL, error))?;
        }
        std::mem::forget(guard);
        Ok(root)
    }));
    let (kind, message) = match outcome {
        Ok(Ok(root)) => return root,
        Ok(Err(failure)) => failure,
        Err(_) => (INTERNAL, String::from("compiler panicked")),
    };
    let message = CString::new(message.replace('\0', " ")).unwrap_or_default();
    // SAFETY: live context; message is NUL-terminated and copied by QuickJS.
    unsafe { ffi::jbq_throw_compile(context, kind, message.as_ptr()) }
}

/// Releases installed native ownership if source publication fails or panics.
struct CompiledRoot {
    context: *mut ffi::Context,
    value: ffi::Value,
}
impl Drop for CompiledRoot {
    fn drop(&mut self) {
        // SAFETY: guard is synchronous, owner-local, and owns this native reference.
        unsafe { ffi::jbq_free(self.context, self.value) };
    }
}

/// Compile to verified image bytes; the flag says whether it is a module.
unsafe fn compile_image(
    context: *mut ffi::Context,
    lease: u64,
    source: &[u16],
    name: &str,
    flags: c_int,
) -> Result<(Vec<u8>, bool), (c_int, String)> {
    let input = SourceInput::from_utf16(source).map_err(|e| (RANGE, e.to_string()))?;
    if lease != 0 {
        // SAFETY: the lease is live for this synchronous callback.
        let (layout, global_var) =
            unsafe { frame_layout(context, lease) }.map_err(|e| (INTERNAL, e))?;
        let image = qjs_compiler_core::eval::compile_eval(&input, name, &layout, global_var)
            .map_err(|e| classify(e, source, name))?;
        return Ok((image.bytes().to_vec(), false));
    }
    let module = flags & EVAL_TYPE_MASK == EVAL_TYPE_MODULE;
    let program = if module {
        qjs_frontend::compile_module_input(&input, name)
    } else if flags & EVAL_FLAG_STRICT != 0 {
        // lunarstorm patch: rquickjs's `Ctx::eval` forces strict mode with
        // `JS_EVAL_FLAG_STRICT`, which jetbunny never passes and this callback
        // ignored: a forced-strict script compiled sloppy (`this` in a plain call
        // was the global object, not `undefined`). The front end's entry point for
        // a script in a strict context takes the strictness without changing the
        // source, so positions stay exact.
        qjs_frontend::compile_eval_program_input(&input, name, true)
    } else {
        qjs_frontend::compile_program_input(&input, name)
    }
    .map_err(|diagnostics| {
        let message = diagnostics
            .first()
            .map(|d| format!("{}{}", d.message, location(source, name, d.span.start)))
            .unwrap_or_else(|| "invalid source".into());
        (SYNTAX, message)
    })?;
    let options = JsEmitOptions {
        debug_markers: flags & EVAL_FLAG_DEBUG != 0,
    };
    let image = qjs_compiler_core::js_emit::emit_program_with_options(&program, &options)
        .map_err(|e| classify(e, source, name))?;
    Ok((image.bytes().to_vec(), module))
}

fn classify(message: String, _source: &[u16], name: &str) -> (c_int, String) {
    let kind = if message.starts_with("capacity") {
        RANGE
    } else {
        SYNTAX
    };
    (kind, format!("{message} (in {name})"))
}

fn location(source: &[u16], name: &str, at: u32) -> String {
    let at = (at as usize).min(source.len());
    let line = 1 + source[..at]
        .iter()
        .filter(|&&u| u == u16::from(b'\n'))
        .count();
    let column = 1 + at
        - source[..at]
            .iter()
            .rposition(|&u| u == u16::from(b'\n'))
            .map_or(0, |p| p + 1);
    format!(" ({name}:{line}:{column})")
}

/// Read the live frame's lexical layout through the lease and verify it; the
/// flag says whether sloppy eval code declares its vars on the global object.
unsafe fn frame_layout(
    context: *mut ffi::Context,
    lease: u64,
) -> Result<(eval::VerifiedEnvLayout, bool), String> {
    let mut view = ffi::EnvView::default();
    // SAFETY: live lease; out-pointer is a local.
    if unsafe { ffi::jbq_eval_environment(context, lease, &mut view) } != 0 {
        return Err("stale eval frame lease".into());
    }
    let bit = |i: u32| view.flags & (1 << i) != 0;
    let flags = FunctionFlags {
        has_prototype: bit(0),
        simple_parameters: bit(1),
        derived_constructor: bit(2),
        need_home_object: bit(3),
        kind: ((view.flags >> 4) & 3) as u8,
        new_target: bit(6),
        super_call: bit(7),
        super_allowed: bit(8),
        arguments_allowed: bit(9),
        backtrace_barrier: bit(10),
    };
    let mut groups: [Vec<eval::EnvBinding>; 3] = Default::default();
    for (kind, count) in [view.args, view.locals, view.captures]
        .into_iter()
        .enumerate()
    {
        for index in 0..count {
            let mut b = ffi::EnvBinding::default();
            // SAFETY: live lease; index below the reported count.
            if unsafe { ffi::jbq_eval_binding(context, lease, kind as u32, index, &mut b) } != 0 {
                return Err("eval frame binding unavailable".into());
            }
            // SAFETY: live lease; returned owned string value is freed below.
            let name = unsafe { binding_name(context, lease, kind as u32, index) }?;
            let (is_const, is_lexical, is_captured, var_kind) = if kind == 2 {
                (
                    b.flags >> 3 & 1 != 0,
                    b.flags >> 4 & 1 != 0,
                    true,
                    (b.flags >> 5) as u8,
                )
            } else {
                (
                    b.flags & 1 != 0,
                    b.flags >> 1 & 1 != 0,
                    b.flags >> 2 & 1 != 0,
                    (b.flags >> 3) as u8,
                )
            };
            groups[kind].push(eval::EnvBinding {
                name,
                is_const,
                is_lexical,
                var_kind,
                scope_level: b.scope_level,
                scope_next: ScopeLink::from_signed(b.scope_next)?,
                is_captured,
                var_ref_idx: b.var_ref_idx,
                initialized: b.initialized != 0,
                live: b.live != 0,
            });
        }
    }
    let [args, locals, refs] = groups;
    let global_var = bit(11);
    eval::verify_env_layout(eval::EnvLayout {
        args,
        locals,
        refs,
        var_ref_count: view.var_refs,
        scope_head: ScopeLink::from_signed(view.scope_head)?,
        strict: view.strict_mode != 0,
        flags,
        ..Default::default()
    })
    .map(|layout| (layout, global_var))
    .map_err(|e| format!("{e:?}"))
}

unsafe fn binding_name(
    context: *mut ffi::Context,
    lease: u64,
    kind: u32,
    index: u32,
) -> Result<Vec<u16>, String> {
    // SAFETY: caller holds the live lease; every owned value is released here.
    unsafe {
        let value = ffi::jbq_eval_binding_name(context, lease, kind, index);
        if ffi::jbq_is_exception(value) != 0 {
            ffi::jbq_free(context, ffi::jbq_take_exception(context));
            return Err("eval binding name unavailable".into());
        }
        let mut length = 0;
        let data = ffi::jbq_string_data(context, value, &mut length);
        let result = if data.is_null() {
            Err("eval binding name unavailable".into())
        } else {
            let units = std::slice::from_raw_parts(data, length).to_vec();
            ffi::jbq_string_free(context, data);
            Ok(units)
        };
        ffi::jbq_free(context, value);
        result
    }
}

/// lunarstorm patch: the bridge declarations the compiler uses, copied
/// verbatim from `lunarstorm-debug`'s `ffi.rs` (jetbunny's private C ABI in
/// `bridge.h`), plus `jbq_set_base_compiler`.
#[allow(dead_code)]
mod bridge {
    use std::ffi::{c_char, c_int, c_void};

    /// An engine `JSValue` packed byte for byte (`jbq_value`).
    #[repr(C)]
    #[derive(Clone, Copy, Debug)]
    pub struct Value {
        /// The packed words.
        pub words: [u64; 2],
    }
    /// The bridge context (`jbq_context`).
    #[repr(C)]
    pub struct Context {
        _private: [u8; 0],
    }
    /// Borrowed source/lease for one synchronous call; returns an owned compiled
    /// object or the exception sentinel. Must not unwind.
    pub type Compiler = unsafe extern "C" fn(
        *mut c_void,
        *mut Context,
        u64,
        *const u16,
        usize,
        *const c_char,
        c_int,
        c_int,
    ) -> Value;
    /// Mirrors JSJetbunnyEnvView.
    #[repr(C)]
    #[derive(Default)]
    pub struct EnvView {
        pub args: u32,
        pub locals: u32,
        pub captures: u32,
        pub var_refs: u32,
        pub strict_mode: u32,
        pub flags: u32,
        pub scope_head: i32,
    }
    /// Mirrors JSJetbunnyEnvBinding.
    #[repr(C)]
    #[derive(Default)]
    pub struct EnvBinding {
        pub name: u32,
        pub scope_level: u32,
        pub scope_next: i32,
        pub flags: u32,
        pub var_ref_idx: u32,
        pub initialized: u32,
        pub live: u32,
    }
    extern "C" {
        pub fn jbq_free(context: *mut Context, value: Value);
        pub fn jbq_is_exception(value: Value) -> c_int;
        pub fn jbq_take_exception(context: *mut Context) -> Value;
        pub fn jbq_string_data(context: *mut Context, value: Value, length: *mut usize)
            -> *const u16;
        pub fn jbq_string_free(context: *mut Context, data: *const u16);
        pub fn jbq_set_compiler(
            context: *mut Context,
            compiler: Option<Compiler>,
            opaque: *mut c_void,
        ) -> c_int;
        /// lunarstorm patch: base compiler of a context the bridge does not own.
        pub fn jbq_set_base_compiler(
            js_context: *mut c_void,
            compiler: Option<Compiler>,
            opaque: *mut c_void,
        ) -> c_int;
        pub fn jbq_eval_environment(context: *mut Context, lease: u64, out: *mut EnvView)
            -> c_int;
        pub fn jbq_eval_binding(
            context: *mut Context,
            lease: u64,
            kind: u32,
            index: u32,
            out: *mut EnvBinding,
        ) -> c_int;
        pub fn jbq_eval_binding_name(
            context: *mut Context,
            lease: u64,
            kind: u32,
            index: u32,
        ) -> Value;
        /// Unsafe: bytes must be a Rust-verified image of this pinned target.
        pub fn jbq_install_verified(
            context: *mut Context,
            bytes: *const u8,
            length: usize,
            prepare: c_int,
        ) -> Value;
        pub fn jbq_throw_compile(context: *mut Context, kind: c_int, message: *const c_char)
            -> Value;
    }
}

# Regenerate the provenance records of ../quickjs from the tree.
#
#   provenance.sh revision          writes quickjs/REVISION
#   provenance.sh jetbunny <dir>    writes quickjs/JETBUNNY-SHA256
#
# REVISION: upstream revision, the patch identities (the `## ` headings of
# PATCHES.md, so the list cannot drift from the document) and the SHA-256 of
# every file in quickjs/ except REVISION itself. Same layout as jetbunny's
# vendor/quickjs-ng/REVISION.
#
# JETBUNNY-SHA256: the files taken from jetbunny byte for byte. <dir> is a
# jetbunny checkout; its commit is recorded. A file is listed only when `cmp`
# finds it identical to jetbunny's copy (vendor/quickjs-ng/, or
# native/quickjs_ng/ for bridge.c and bridge.h). Files that differ are
# Lunarstorm deltas, described in PATCHES.md and hashed in REVISION only.
#
# Both files are checked by tests/provenance.rs. Temporary output is a hidden
# file so the `*` glob never hashes it.
set -eu
cd "$(dirname "$0")/../quickjs"

case "${1:-}" in
revision)
	patches=$(sed -n 's/^## //p' PATCHES.md | awk 'BEGIN{ORS=""} NR>1{print " + "} {print}')
	{
		echo "Upstream: https://github.com/quickjs-ng/quickjs"
		echo "Revision: 7b5f588e0f9b643e2996f291bfc861abeaceddc2"
		echo "Version: 0.17.0"
		echo "Build inputs, edited in place with $patches (see PATCHES.md). Generated by ../scripts/provenance.sh. SHA-256:"
		for f in *; do
			[ "$f" = REVISION ] && continue
			shasum -a 256 "$f"
		done
	} > .REVISION.new
	mv .REVISION.new REVISION
	;;
jetbunny)
	j=${2:?jetbunny checkout}
	commit=$(git -C "$j" rev-parse HEAD)
	{
		echo "Jetbunny: $commit"
		echo "Files identical to jetbunny's copy (vendor/quickjs-ng/, bridge.* from native/quickjs_ng/). SHA-256:"
		for f in *; do
			case "$f" in
			REVISION | JETBUNNY-SHA256) continue ;;
			bridge.c | bridge.h) src="$j/native/quickjs_ng/$f" ;;
			*) src="$j/vendor/quickjs-ng/$f" ;;
			esac
			[ -f "$src" ] && cmp -s "$f" "$src" && shasum -a 256 "$f"
		done
		true
	} > .JETBUNNY-SHA256.new
	mv .JETBUNNY-SHA256.new JETBUNNY-SHA256
	;;
*)
	echo "usage: $0 revision | jetbunny <dir>" >&2
	exit 2
	;;
esac
